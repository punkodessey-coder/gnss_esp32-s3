#!/usr/bin/env python3
"""Train a robust, tiny GNSS telemetry baseline from ai_dataset.csv.

The output is a C++ header consumed by src/ai_ml.h. This is unsupervised
normal-profile fitting (median + scaled MAD), not a neural network classifier.
"""
import argparse
import csv
import math
import statistics
from pathlib import Path

FEATURES = [
    ("hdop", "hdop"),
    ("sat_used", "satellite count used"),
    ("gsv_snr_avg", "average GSV signal"),
    ("accel_magnitude", "acceleration magnitude"),
    ("gyro_magnitude", "gyro magnitude"),
    ("sat_visible", "visible satellites"),
]
MIN_SAMPLES = 30


def number(value):
    try:
        x = float(value)
        return x if math.isfinite(x) else None
    except (TypeError, ValueError):
        return None


def train(input_path):
    values = [[] for _ in FEATURES]
    rows = 0
    with open(input_path, newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        required = {"hdop", "sat_used", "gsv_snr_avg", "accel_magnitude",
                    "gyro_magnitude", "sat_visible"}
        if not reader.fieldnames or not required.issubset(set(reader.fieldnames)):
            raise ValueError("CSV не содержит все необходимые столбцы ai_dataset.csv")
        for row in reader:
            rows += 1
            # Only normal, non-anomalous examples contribute to the baseline.
            if str(row.get("anomaly", "0")).strip() in {"1", "true", "True"}:
                continue
            fix = str(row.get("fix", "0")).strip() in {"1", "true", "True"}
            for i, (column, _) in enumerate(FEATURES):
                if column in {"hdop", "sat_used"} and not fix:
                    continue
                x = number(row.get(column))
                if x is None:
                    continue
                if column == "hdop" and x <= 0: continue
                if column in {"sat_used", "sat_visible"} and x <= 0: continue
                if column == "gsv_snr_avg" and x <= 0: continue
                if column in {"accel_magnitude", "gyro_magnitude"} and x < 0: continue
                values[i].append(x)
    if rows < MIN_SAMPLES:
        raise ValueError(f"Нужно не менее {MIN_SAMPLES} строк, найдено {rows}")
    centers, scales, mask = [], [], 0
    for i, series in enumerate(values):
        if len(series) < MIN_SAMPLES:
            centers.append(0)
            scales.append(1)
            continue
        center = statistics.median(series)
        mad = statistics.median(abs(x - center) for x in series)
        # 1.4826 converts MAD to a robust Gaussian-equivalent sigma.
        scale = max(0.25 if i in (0, 2, 3, 4) else 1.0, 1.4826 * mad)
        centers.append(center)
        scales.append(scale)
        mask |= 1 << i
    if not (mask & ((1 << 2) | (1 << 5) | (1 << 3) | (1 << 4) | (1 << 0) | (1 << 1))):
        raise ValueError("Недостаточно заполненных измерений для обучения")
    return rows, centers, scales, mask


def render(rows, centers, scales, mask, threshold=4.0):
    def q(x):
        return max(1, min(65535, int(round(x * 100))))
    c = ", ".join(str(q(x)) for x in centers)
    s = ", ".join(str(q(x)) for x in scales)
    return f"""#pragma once
#include <stdint.h>

// Generated by scripts/train_ai_model.py. Robust median/MAD baseline.
namespace GnssTrainedModel {{
static constexpr bool enabled = true;
static constexpr uint8_t featureMask = {mask};
static constexpr uint16_t centerQ[6] = {{{c}}};
static constexpr uint16_t scaleQ[6] = {{{s}}};
static constexpr uint16_t thresholdQ = {q(threshold)};
static constexpr uint32_t trainingSamples = {rows};
}}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", help="exported ai_dataset.csv")
    parser.add_argument("-o", "--output", default="src/ai_trained_model.h")
    parser.add_argument("--threshold", type=float, default=4.0)
    args = parser.parse_args()
    if not 2.5 <= args.threshold <= 10:
        parser.error("--threshold должен быть от 2.5 до 10")
    rows, centers, scales, mask = train(args.csv)
    Path(args.output).write_text(render(rows, centers, scales, mask, args.threshold),
                                 encoding="utf-8")
    print(f"Модель подготовлена: строк={rows}, признаков={mask.bit_count()}, "
          f"порог={args.threshold:.2f} sigma")
    print(f"Файл: {args.output}")


if __name__ == "__main__":
    main()
