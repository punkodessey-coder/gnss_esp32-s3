#!/usr/bin/env python3
"""Train a robust GNSS-only normal profile from ai_dataset.csv.

This is an unsupervised median/MAD baseline, not a neural network classifier.
Only valid FIX rows without a current anomaly are used. IMU features are
intentionally disabled until the dataset contains stable, comparable sessions.
"""
import argparse
import csv
import math
import json
import statistics
from pathlib import Path

FEATURES = [
    ("hdop", "HDOP"),
    ("sat_used", "satellites used"),
    ("gsv_snr_avg", "average GSV signal"),
    ("accel_magnitude", "acceleration magnitude"),
    ("gyro_magnitude", "gyro magnitude"),
    ("sat_visible", "visible satellites"),
]
# GNSS-only features. Bits 3 and 4 (IMU) remain reserved for later training.
TRAINABLE_INDICES = (0, 1, 2, 5)
MIN_SAMPLES = 30


def number(value):
    try:
        x = float(value)
        return x if math.isfinite(x) else None
    except (TypeError, ValueError):
        return None


def is_true(value):
    return str(value or "").strip().lower() in {"1", "true", "yes"}


def haversine_m(lat1, lon1, lat2, lon2):
    radius = 6371000.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = math.radians(lat2-lat1), math.radians(lon2-lon1)
    a = math.sin(dp/2)**2 + math.cos(p1)*math.cos(p2)*math.sin(dl/2)**2
    return 2*radius*math.atan2(math.sqrt(a), math.sqrt(1-a))


def train(input_path, reference=None, radius_m=50.0):
    values = [[] for _ in FEATURES]
    training_rows = 0
    with open(input_path, newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        required = {"fix", "anomaly", "hdop", "sat_used", "gsv_snr_avg", "sat_visible"}
        if not reader.fieldnames or not required.issubset(set(reader.fieldnames)):
            raise ValueError("CSV не содержит необходимые столбцы GNSS-профиля")
        for row in reader:
            # A normal baseline must be learned only from valid navigation fixes.
            if not is_true(row.get("fix")) or is_true(row.get("anomaly")):
                continue
            if reference is not None:
                row_lat, row_lon = number(row.get("lat")), number(row.get("lon"))
                if row_lat is None or row_lon is None:
                    continue
                if haversine_m(reference[0], reference[1], row_lat, row_lon) > radius_m:
                    continue
            training_rows += 1
            for i in TRAINABLE_INDICES:
                column, _ = FEATURES[i]
                x = number(row.get(column))
                if x is None or x <= 0:
                    continue
                values[i].append(x)

    if training_rows < MIN_SAMPLES:
        raise ValueError(
            f"Нужно не менее {MIN_SAMPLES} нормальных строк с FIX, найдено {training_rows}"
        )

    centers, scales, mask = [], [], 0
    for i, _ in enumerate(FEATURES):
        if i not in TRAINABLE_INDICES or len(values[i]) < MIN_SAMPLES:
            centers.append(0)
            scales.append(1)
            continue
        series = values[i]
        center = statistics.median(series)
        mad = statistics.median(abs(x - center) for x in series)
        # 1.4826 converts MAD to a robust Gaussian-equivalent sigma.
        floor = 0.25 if i in (0, 2) else 1.0
        scale = max(floor, 1.4826 * mad)
        centers.append(center)
        scales.append(scale)
        mask |= 1 << i

    if not mask:
        raise ValueError("Недостаточно заполненных GNSS-измерений для обучения")
    return training_rows, centers, scales, mask


def render(rows, centers, scales, mask, threshold=4.0, role='normal_baseline'):
    def q(x):
        return max(1, min(65535, int(round(x * 100))))
    c = ", ".join(str(q(x)) for x in centers)
    s = ", ".join(str(q(x)) for x in scales)
    return f"""#pragma once
#include <stdint.h>

// Generated by scripts/train_ai_model.py. GNSS-only median/MAD profile.
namespace GnssTrainedModel {{
static constexpr bool enabled = true;
static constexpr const char* role = "{role}";
static constexpr uint8_t featureMask = {mask};
static constexpr uint16_t centerQ[6] = {{{c}}};
static constexpr uint16_t scaleQ[6] = {{{s}}};
static constexpr uint16_t thresholdQ = {q(threshold)};
static constexpr uint32_t trainingSamples = {rows};
}}
"""


def render_json(rows, centers, scales, mask, threshold=4.0, role="normal_baseline"):
    return json.dumps({
        "format": "gnss-ai-profile-v1", "role": role, "feature_mask": mask,
        "threshold": threshold, "training_samples": rows,
        "center": centers, "scale": scales
    }, ensure_ascii=False, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", help="exported ai_dataset.csv")
    parser.add_argument("-o", "--output", default="src/ai_trained_model.h")
    parser.add_argument("--threshold", type=float, default=4.0)
    parser.add_argument("--reference-lat", type=float, help="реальная широта только для отбора строк CSV")
    parser.add_argument("--reference-lon", type=float, help="реальная долгота только для отбора строк CSV")
    parser.add_argument("--radius-m", type=float, default=50.0, help="радиус допуска в метрах")
    parser.add_argument("--json-output", default="gnss-ai-profile.json")
    parser.add_argument("--role", choices=("normal_baseline", "spoofing_signature"), default="normal_baseline")
    args = parser.parse_args()
    if not 2.5 <= args.threshold <= 10:
        parser.error("--threshold должен быть от 2.5 до 10")
    if (args.reference_lat is None) != (args.reference_lon is None):
        parser.error("--reference-lat и --reference-lon нужно указывать вместе")
    if not 1 <= args.radius_m <= 500:
        parser.error("--radius-m должен быть от 1 до 500")
    reference = (args.reference_lat, args.reference_lon) if args.reference_lat is not None else None
    if reference and not (-90 <= reference[0] <= 90 and -180 <= reference[1] <= 180):
        parser.error("координаты вне диапазона")
    rows, centers, scales, mask = train(args.csv, reference, args.radius_m)
    Path(args.output).write_text(render(rows, centers, scales, mask, args.threshold, args.role),
                                 encoding="utf-8")
    Path(args.json_output).write_text(render_json(rows, centers, scales, mask, args.threshold, args.role),
                                      encoding="utf-8")
    print(f"Модель подготовлена: нормальных FIX-строк={rows}, "
          f"GNSS-признаков={mask.bit_count()}, порог={args.threshold:.2f} sigma")
    print(f"Файл заголовка: {args.output}")
    print(f"JSON-профиль: {args.json_output}")


if __name__ == "__main__":
    main()
